import { expect, test } from '@playwright/test'
import { setTransformationTime } from './controls'

test('the map supports inspection and all implemented destinations', async ({ page }) => {
  await page.goto('./?solid=cube')
  await setTransformationTime(page,0.5)
  await page.getByRole('button', { name: 'Map', exact: true }).click()
  const map = page.getByRole('dialog', { name: 'Transformation map' })
  await expect(map.getByRole('button', { name: /^Inspect / })).toHaveCount(9)
  await page.screenshot({ path: test.info().outputPath('relationship-map.png'), animations: 'disabled' })
  await map.getByRole('button', { name: 'Inspect Dodecahedron', exact: true }).click()
  await expect(map.getByRole('heading', { name: 'From Dodecahedron' })).toBeVisible()
  await expect(map.getByRole('button', { name: 'Stellation → Great dodecahedron · 2-stage route', exact: true })).toBeEnabled()
  await map.getByRole('button', { name: 'Stellation → Small stellated dodecahedron', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Small stellated dodecahedron', exact: true })).toBeVisible()
  await expect(map).not.toBeVisible()
  await page.getByRole('button', { name: 'Choose stellation destination' }).click()
  await expect(page.getByRole('button', { name: 'Dodecahedron', exact: true })).toBeVisible()
})

test('long action labels stay on one line and color follows reset', async ({ page }) => {
  await page.goto('./?solid=great-dodecahedron')
  for (const name of ['Dual','Stellate']) {
    const button = page.getByRole('button', { name, exact: true })
    const box = await button.boundingBox()
    expect(box!.height).toBeLessThan(50)
    expect(await button.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  }
  const reset = await page.getByRole('button', { name: 'Reset view', exact: true }).boundingBox()
  const color = await page.getByLabel('Color', { exact: true }).boundingBox()
  expect(color!.x).toBeGreaterThanOrEqual(reset!.x+reset!.width)
  const opacity = await page.getByRole('button', { name: 'Toggle face opacity' }).boundingBox()
  expect(opacity!.x).toBeGreaterThanOrEqual(color!.x+color!.width)
  expect(Math.abs(opacity!.y-color!.y)).toBeLessThan(2)
  await expect(page.getByRole('button', { name: 'Dual', exact: true })).toHaveClass(/btn-info/)
  await expect(page.getByRole('button', { name: 'Stellate', exact: true })).toHaveClass(/btn-warning/)
  await expect(page.getByText(/choose a transformation|New actions unlock/)).toHaveCount(0)
  await expect(page.locator('[data-testid="transformation-status"]')).toHaveCount(0)
  const stage = page.getByLabel('Interactive 3D model of a Great dodecahedron')
  expect((await stage.boundingBox())!.height).toBeGreaterThan(100)
  if (page.viewportSize()!.width >= 768) {
    const player = await page.getByRole('group', { name: 'Transformation player' }).boundingBox()
    expect(player!.x+player!.width/2).toBeCloseTo(page.viewportSize()!.width/2,-1)
  }
  await expect(page.locator('canvas')).toHaveAttribute('data-engine', /three.js/)
  await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  await page.screenshot({ path: test.info().outputPath('hud.png') })
})

test('player stepping and milestones hold intermediate geometry', async ({ page }) => {
  await page.goto('./?solid=cube')
  await expect(page.getByRole('button', { name: 'Seek to transformation milestone' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '50%', exact: true })).toHaveCount(0)
  const slider = page.getByRole('slider', { name: /Transformation progress/ })
  await slider.fill('0.5')
  await expect(slider).toHaveValue('0.5')
  await page.getByRole('button', { name: 'Step transformation forward' }).click()
  await expect(slider).toHaveValue('0.51')
  await page.getByRole('button', { name: 'Step transformation backward' }).click()
  await expect(slider).toHaveValue('0.5')
  await page.getByRole('button', { name: 'Go to transformation end' }).click()
  await expect(page.getByRole('heading', { name: 'Octahedron', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Go to transformation start' }).click()
  await expect(page.getByRole('heading', { name: 'Cube', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Explain this transformation' }).click()
  await expect(page.getByRole('dialog')).toContainText('cuboctahedron')
})

test('history restores the reached geometry and its camera view', async ({ page }) => {
  await page.goto('./?solid=dodecahedron')
  await setTransformationTime(page,0.5)
  await page.getByRole('button', { name: 'Stellate', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Small stellated dodecahedron', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Zoom out', exact: true }).click()
  await expect(page.locator('canvas')).toHaveAttribute('data-engine', /three.js/)
  await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  const before = await page.locator('canvas').screenshot()
  await page.getByRole('button', { name: 'Dual', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Great dodecahedron', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await page.getByRole('button', { name: '2. Small stellated dodecahedron', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Small stellated dodecahedron', exact: true })).toBeVisible()
  await expect(page.locator('canvas')).toHaveAttribute('data-engine', /three.js/)
  await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  const after = await page.locator('canvas').screenshot()
  expect(after.equals(before)).toBe(true)
})
